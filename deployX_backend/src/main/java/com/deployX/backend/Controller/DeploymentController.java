package com.deployX.backend.Controller;

import com.deployX.backend.Service.DeploymentService;
import com.deployX.backend.Service.EnvironmentVariableService;
import com.deployX.backend.io.*;
import io.swagger.v3.oas.annotations.Operation;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;
import java.util.UUID;

@RestController
@RequestMapping("/deployment")
@RequiredArgsConstructor
public class DeploymentController {
    private final DeploymentService deploymentService;
    private final EnvironmentVariableService envService;


    @Operation(
            summary = "Analyze a repository for deployment",
            description = """
                Analyzes the repository specified in the request to gather
                information required for deployment.

                The request must be associated with an authenticated user.
                The user's email is obtained from the HTTP request attribute
                'deployxUserEmail'.

                Returns the deployment analysis generated by the
                DeploymentService.
                """
    )
    @PostMapping("/analyze")
    public deploymentResponse analyze(@RequestBody deploymentRequest request , HttpServletRequest httpServletRequest){

        String email = (String) httpServletRequest.getAttribute("deployxUserEmail");

        if(email == null){
            throw new ResponseStatusException(
                    HttpStatus.UNAUTHORIZED,
                    "User not Found"
            );
        }
        return deploymentService.analyzeRepository( email , request);
    }



    @Operation(
            summary = "Create a new deployment",
            description = """
                Creates a deployment using the repository and other
                deployment information supplied in the request.

                The authenticated user's email is used to associate the
                deployment with the correct user.

                Returns a DeploymentCreationResponse when the deployment
                is created successfully. The endpoint responds with
                HTTP 201 Created.

                Requests without a recognized authenticated user's email
                are rejected with HTTP 401 Unauthorized.
                """
    )
    @PostMapping("/create")
    @ResponseStatus(HttpStatus.CREATED)
    public DeploymentCreationResponse createDeployment(
            @RequestBody deploymentRequest request,
            HttpServletRequest httpServletRequest) {

        String email = (String) httpServletRequest
                .getAttribute("deployxUserEmail");

        if (email == null || email.isBlank()) {
            throw new ResponseStatusException(
                    HttpStatus.UNAUTHORIZED,
                    "User not found"
            );
        }

        return deploymentService.createDeployment(email , request);
    }


    @Operation(
            summary = "Add or replace deployment environment variables",
            description = """
                Saves the environment variables associated with a
                specific deployment.

                Provide the deployment UUID in the URL and a JSON array
                containing the variable names, values, and secret flags.

                The operation delegates to EnvironmentVariableService to
                replace the deployment's existing environment-variable set.
                Environment-variable values are encrypted before storage
                by the service implementation.

                The authenticated user must own the specified deployment.
                The response contains variable names and secret flags,
                not the variable values.

                Returns HTTP 200 OK when the operation succeeds, or
                HTTP 401 Unauthorized when the user's email is unavailable.
                """
    )
    @PutMapping(value = "/{deploymentId}/environment-variables")
    public ResponseEntity<List<EnvironmentVariableResponse>> addVariable(
            @PathVariable UUID deploymentId,
            @Valid @RequestBody List<@Valid EnvironmentVariableRequest> variables,
            HttpServletRequest request
    ){

        String email = (String) request.getAttribute("deployxUserEmail");

        if (email == null || email.isBlank()) {
            return ResponseEntity.status(HttpStatus.UNAUTHORIZED).build();
        }

        List<EnvironmentVariableResponse> response =
                envService.replaceVariable(
                        email,
                        deploymentId,
                        variables
                );

        return ResponseEntity.ok(response);

    }

    @Operation(
            summary = "Get deployment environment-variable metadata",
            description = """
                Retrieves the environment-variable metadata associated
                with the specified deployment UUID.

                The authenticated user's email is used to verify access
                to the deployment.

                Returns a list containing each environment variable's
                name and secret flag. Variable values are not returned
                by this endpoint.

                Returns HTTP 200 OK when the request succeeds, or
                HTTP 401 Unauthorized when the user's email is unavailable.
                """
    )
    @GetMapping("/{deploymentId}/environment-variables")
    public ResponseEntity<List<EnvironmentVariableResponse>> getEnvironmentVariables(
            @PathVariable UUID deploymentId,
            HttpServletRequest request) {

        String email = (String) request.getAttribute("deployxUserEmail");

        if (email == null || email.isBlank()) {
            return ResponseEntity.status(HttpStatus.UNAUTHORIZED).build();
        }

        List<EnvironmentVariableResponse> response =
                envService.getVariables(
                        email,
                        deploymentId
                );

        return ResponseEntity.ok(response);
    }


}
